//! montrs-icons collection codegen.
//!
//! Downloads the upstream SVG tarballs from GitHub (codeload), extracts only
//! the `.svg` files, and generates:
//!   - `../src/collections/data.rs` — the per-collection `CollectedGlyph` tables
//!   - `../src/collections/catalog.rs` — collection metadata + helpers
//!   - `THIRD_PARTY_NOTICES.md` — license compliance records (root of the repo)
//!
//! Pure Rust: the only external dependencies are crates.io (ureq, flate2, tar).
//! No node, no JS, no Python. Run: `cargo run --manifest-path codegen/Cargo.toml`

